#[test]
fn fp_legacy_matches_every_original_decimal() {
    let params = fp_legacy::static_params();
    assert_eq!(params.mds.len(), 3);
    assert_eq!(params.round_constants.len(), 100);
    let actual: Vec<Fp> = params
        .mds
        .iter()
        .flatten()
        .chain(params.round_constants.iter().flatten())
        .copied()
        .collect();
    assert_eq!(actual.len(), FP_DECIMAL.len());
    for (index, (got, decimal)) in actual.iter().zip(FP_DECIMAL).enumerate() {
        let expected = Fp::from_str(decimal).unwrap();
        assert!(!expected.is_zero(), "unexpected zero at {index}");
        assert_eq!(*got, expected, "legacy constant {index}");
        assert!(got.into_bigint() < Fp::MODULUS);
    }
}

